package chess.enums;

/**
 * ChessPieceType.java
 * Defines the six supported chess piece types.
 *
 * @author Aredth Sanchez
 */
public enum ChessPieceType {

    /**
     * Pawn piece type.
     */
    PAWN,
    /**
     * Rook piece type.
     */
    ROOK,
    /**
     * Bishop piece type.
     */
    BISHOP,
    /**
     * Knight piece type.
     */
    KNIGHT,
    /**
     * King piece type.
     */
    KING,
    /**
     * Queen piece type.
     */
    QUEEN

}
